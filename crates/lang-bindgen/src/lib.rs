use syn::{FnArg, Item, ReturnType, Type};

pub fn sync_project_dynamic(
    toml_path: &std::path::Path,
) -> Result<(std::path::PathBuf, codegen::SyncSummary), String> {
    let project_dir = toml_path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| std::path::Path::new("."));
    let content = std::fs::read_to_string(toml_path)
        .map_err(|e| format!("Failed to read {}: {}", toml_path.display(), e))?;
    let deps = scanner::parse_striv_toml_full(&content);
    if deps.is_empty() {
        return Err("No [dependencies] in striv.toml".to_string());
    }

    let host_dir = project_dir.join(".striv-host");
    let dll_name = if cfg!(windows) {
        "striv_host_bridge.dll"
    } else if cfg!(target_os = "macos") {
        "libstriv_host_bridge.dylib"
    } else {
        "libstriv_host_bridge.so"
    };
    let dll_path = host_dir.join("target").join("release").join(dll_name);
    let hash_file = host_dir.join(".bridge_hash");

    // Hash dependencies + bindgen version
    let mut hash: u64 = 0xcbf29ce484222325;
    for b in content.as_bytes().iter().chain(b"striv-bindgen-2.0-v3") {
        hash ^= *b as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    let hash_str = format!("{:016x}", hash);

    if dll_path.exists() {
        if let Ok(prev) = std::fs::read_to_string(&hash_file) {
            if prev.trim() == hash_str {
                let summary = codegen::SyncSummary {
                    crate_count: deps.len(),
                    struct_count: 0,
                    enum_count: 0,
                    fn_count: 0,
                };
                return Ok((dll_path, summary));
            }
        }
    }

    let sources = scanner::resolve_crate_sources_in(project_dir, &deps);
    let apis: Vec<scanner::CrateApi> = sources
        .iter()
        .map(|(name, path)| scanner::scan_crate_api(name, path))
        .collect();
    let dep_names: Vec<String> = deps.iter().map(|(n, _)| n.replace('-', "_")).collect();
    let (code, meta_json, summary) = codegen::emit_dynamic_bridge_crate(&apis, &dep_names);

    std::fs::write(host_dir.join("src").join("lib.rs"), code)
        .map_err(|e| format!("Failed to write .striv-host/src/lib.rs: {}", e))?;
    std::fs::write(host_dir.join("striv_bridge_meta.json"), meta_json)
        .map_err(|e| format!("Failed to write striv_bridge_meta.json: {}", e))?;

    let manifest = host_dir.join("Cargo.toml");
    let status = std::process::Command::new("cargo")
        .args([
            "build",
            "--release",
            "--manifest-path",
            manifest.to_str().unwrap_or(".striv-host/Cargo.toml"),
        ])
        .status()
        .map_err(|e| format!("Failed to run cargo build for .striv-host: {}", e))?;
    if !status.success() {
        return Err("cargo build --release for .striv-host failed".to_string());
    }
    let _ = std::fs::write(&hash_file, hash_str);
    Ok((dll_path, summary))
}

pub fn sync_project(toml_path: &str) -> (String, codegen::SyncSummary) {
    let content = std::fs::read_to_string(toml_path)
        .unwrap_or_else(|e| panic!("Failed to read {}: {}", toml_path, e));
    let deps = scanner::parse_striv_toml(&content);
    let sources = scanner::resolve_crate_sources(&deps);
    let apis: Vec<scanner::CrateApi> = sources
        .iter()
        .map(|(name, path)| scanner::scan_crate_api(name, path))
        .collect();
    codegen::emit_crate_bridge(&apis)
}

#[derive(Debug, Clone)]
pub struct ExportedFn {
    pub striv_name: String,
    pub c_symbol: String,
    pub param_count: usize,
    pub has_return: bool,
}

/// Parses Rust source with `syn` and generates:
/// 1. `#[unsafe(no_mangle)] pub extern "C"` wrapper functions for the host
/// 2. Metadata for Cranelift & VS Code autocompletion
pub fn generate_rust_bridge(rust_source: &str) -> (String, Vec<ExportedFn>) {
    let syntax_tree = syn::parse_file(rust_source).expect("Failed to parse Rust bridge file");

    let mut generated_rust =
        String::from("// AUTO-GENERATED BY `striv bindgen` - DO NOT EDIT MANUALLY\n\n");
    generated_rust.push_str(rust_source);
    generated_rust.push_str("\n\n");
    let mut exported = Vec::new();

    for item in syntax_tree.items {
        if let Item::Fn(func) = item {
            if !matches!(func.vis, syn::Visibility::Public(_)) {
                continue;
            }

            let fn_name = func.sig.ident.to_string();
            let c_symbol = format!("striv_ext_{}", fn_name);
            let mut param_names = Vec::new();
            let mut c_params = Vec::new();

            for (i, input) in func.sig.inputs.iter().enumerate() {
                if let FnArg::Typed(pat_type) = input {
                    let p_name = format!("arg{}", i);
                    param_names.push(p_name.clone());
                    c_params.push(format!("{}: i64", p_name));
                    let _ = &pat_type.ty;
                }
            }

            let has_return = !matches!(func.sig.output, ReturnType::Default);

            generated_rust.push_str(&format!(
                "#[unsafe(no_mangle)]\npub extern \"C\" fn {}({}) -> i64 {{\n",
                c_symbol,
                c_params.join(", "),
            ));

            if has_return {
                generated_rust.push_str(&format!(
                    "    {}({}) as i64\n",
                    fn_name,
                    param_names.join(", ")
                ));
            } else {
                generated_rust.push_str(&format!(
                    "    {}({});\n    0\n",
                    fn_name,
                    param_names.join(", ")
                ));
            }
            generated_rust.push_str("}\n\n");

            exported.push(ExportedFn {
                striv_name: fn_name,
                c_symbol,
                param_count: param_names.len(),
                has_return,
            });
        }
    }

    generated_rust
        .push_str("pub fn exported_symbols() -> &'static [(&'static str, &'static str, *const u8, &'static str)] {\n    &[\n");
    for ex in &exported {
        let sig = format!(
            "{}->{}",
            "i".repeat(ex.param_count),
            if ex.has_return { "i" } else { "i" }
        );
        generated_rust.push_str(&format!(
            "        (\"{}\", \"{}\", {} as *const u8, \"{}\"),\n",
            ex.striv_name, ex.c_symbol, ex.c_symbol, sig
        ));
    }
    generated_rust.push_str("    ]\n}\n");

    (generated_rust, exported)
}

#[allow(dead_code)]
fn is_i64(ty: &Type) -> bool {
    matches!(ty, Type::Path(p) if p.path.is_ident("i64"))
}
