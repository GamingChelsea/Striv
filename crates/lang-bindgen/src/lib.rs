use syn::{FnArg, Item, ReturnType, Type};

#[derive(Debug, Clone)]
pub struct ExportedFn {
    pub striv_name: String,
    pub c_symbol: String,
    pub param_count: usize,
    pub has_return: bool,
}

/// Parses Rust source with `syn` and generates:
/// 1. `#[unsafe(no_mangle)] pub extern "C"` wrapper functions for the host
/// 2. Metadata for Cranelift & VS Code autocompletion
pub fn generate_rust_bridge(rust_source: &str) -> (String, Vec<ExportedFn>) {
    let syntax_tree = syn::parse_file(rust_source).expect("Failed to parse Rust bridge file");

    let mut generated_rust =
        String::from("// AUTO-GENERATED BY `striv bindgen` - DO NOT EDIT MANUALLY\n\n");
    generated_rust.push_str(rust_source);
    generated_rust.push_str("\n\n");
    let mut exported = Vec::new();

    for item in syntax_tree.items {
        if let Item::Fn(func) = item {
            if !matches!(func.vis, syn::Visibility::Public(_)) {
                continue;
            }

            let fn_name = func.sig.ident.to_string();
            let c_symbol = format!("striv_ext_{}", fn_name);
            let mut param_names = Vec::new();
            let mut c_params = Vec::new();

            for (i, input) in func.sig.inputs.iter().enumerate() {
                if let FnArg::Typed(pat_type) = input {
                    let p_name = format!("arg{}", i);
                    param_names.push(p_name.clone());
                    c_params.push(format!("{}: i64", p_name));
                    let _ = &pat_type.ty;
                }
            }

            let has_return = !matches!(func.sig.output, ReturnType::Default);

            generated_rust.push_str(&format!(
                "#[unsafe(no_mangle)]\npub extern \"C\" fn {}({}) -> i64 {{\n",
                c_symbol,
                c_params.join(", "),
            ));

            if has_return {
                generated_rust.push_str(&format!(
                    "    {}({}) as i64\n",
                    fn_name,
                    param_names.join(", ")
                ));
            } else {
                generated_rust.push_str(&format!(
                    "    {}({});\n    0\n",
                    fn_name,
                    param_names.join(", ")
                ));
            }
            generated_rust.push_str("}\n\n");

            exported.push(ExportedFn {
                striv_name: fn_name,
                c_symbol,
                param_count: param_names.len(),
                has_return,
            });
        }
    }

    generated_rust
        .push_str("pub fn exported_symbols() -> &'static [(&'static str, &'static str, *const u8, usize)] {\n    &[\n");
    for ex in &exported {
        generated_rust.push_str(&format!(
            "        (\"{}\", \"{}\", {} as *const u8, {}),\n",
            ex.striv_name, ex.c_symbol, ex.c_symbol, ex.param_count
        ));
    }
    generated_rust.push_str("    ]\n}\n");

    (generated_rust, exported)
}

#[allow(dead_code)]
fn is_i64(ty: &Type) -> bool {
    matches!(ty, Type::Path(p) if p.path.is_ident("i64"))
}
